# -*- coding: utf-8 -*-
"""Replot SDG stochastic prefetching figure from existing CSV/JSON artifacts.

This script is intentionally separated from simulation generation so that the
plot can be iterated quickly without regenerating turn-level synthetic data.
"""

from __future__ import annotations

import argparse
import csv
import json
from dataclasses import dataclass
from pathlib import Path

_THIS_DIR = Path(__file__).resolve().parent
_DEFAULT_CSV = _THIS_DIR / "stochastic_prefetching_turn_evolution.csv"
_DEFAULT_JSON = _THIS_DIR / "stochastic_prefetching_turn_evolution.json"
_DEFAULT_OUTPUT_PREFIX = _THIS_DIR / "stochastic_prefetching_turn_evolution"


@dataclass(frozen=True)
class PlotPreset:
    """Style preset for publication plotting."""

    figure_width: float
    figure_height: float
    font_size: int
    axes_labelsize: int
    axes_titlesize: int
    legend_fontsize: int
    tick_labelsize: int
    legend_anchor_y: float


# Sized for typical double-column paper layout while preserving readability.
_PAPER_2COL_PRESET = PlotPreset(
    figure_width=8,
    figure_height=5,
    font_size=20,
    axes_labelsize=22,
    axes_titlesize=22,
    legend_fontsize=20,
    tick_labelsize=20,
    legend_anchor_y=1.32,
)
_PLOT_LINEWIDTH = 4
_PLOT_MARKERSIZE = 8


def _load_series_from_csv(
    csv_path: Path,
) -> tuple[list[int], list[float], list[float], list[float], list[float]]:
    """Load turn-level series from CSV artifact.

    Args:
        csv_path (`Path`):
            Path to CSV generated by the simulation script.

    Returns:
        `tuple[list[int], list[float], list[float], list[float], list[float]]`:
            Turns, reactive latency, proactive latency, reactive cold-start,
            proactive cold-start.
    """
    turns: list[int] = []
    reactive_latency_ms: list[float] = []
    complete_latency_ms: list[float] = []
    reactive_cold_starts: list[float] = []
    complete_cold_starts: list[float] = []

    with csv_path.open("r", encoding="utf-8", newline="") as file:
        reader = csv.DictReader(file)
        for row in reader:
            turns.append(int(row["turn"]))
            reactive_latency_ms.append(float(row["reactive_latency_ms"]))
            complete_latency_ms.append(float(row["complete_latency_ms"]))
            reactive_cold_starts.append(
                float(row["reactive_cold_start_sandbox_count"]),
            )
            complete_cold_starts.append(
                float(row["complete_cold_start_sandbox_count"]),
            )

    if not turns:
        raise ValueError(f"No rows found in CSV: {csv_path}")

    return (
        turns,
        reactive_latency_ms,
        complete_latency_ms,
        reactive_cold_starts,
        complete_cold_starts,
    )


def _validate_with_json(json_path: Path, expected_turn_count: int) -> None:
    """Validate consistency between CSV and JSON artifact.

    Args:
        json_path (`Path`):
            JSON artifact path.
        expected_turn_count (`int`):
            Turn count loaded from CSV.
    """
    payload = json.loads(json_path.read_text(encoding="utf-8"))
    turn_series = payload.get("turn_series", [])
    if len(turn_series) != expected_turn_count:
        raise ValueError(
            "CSV/JSON turn count mismatch: "
            f"csv={expected_turn_count}, json={len(turn_series)}",
        )


def plot_dual_axis_figure(
    output_prefix: Path,
    turns: list[int],
    reactive_latency_ms: list[float],
    complete_latency_ms: list[float],
    reactive_cold_starts: list[float],
    complete_cold_starts: list[float],
) -> None:
    """Render the dual-axis line figure with paper-2col fonts.

    Args:
        output_prefix (`Path`):
            Output prefix without suffix.
        turns (`list[int]`):
            Dialogue turns.
        reactive_latency_ms (`list[float]`):
            Reactive latency series.
        complete_latency_ms (`list[float]`):
            Proactive latency series.
        reactive_cold_starts (`list[float]`):
            Reactive per-turn cold-start series.
        complete_cold_starts (`list[float]`):
            Proactive per-turn cold-start series.
    """
    import matplotlib.pyplot as plt

    preset = _PAPER_2COL_PRESET

    plt.rcParams.update(
        {
            "font.size": preset.font_size,
            "axes.labelsize": preset.axes_labelsize,
            "axes.titlesize": preset.axes_titlesize,
            "legend.fontsize": preset.legend_fontsize,
            "xtick.labelsize": preset.tick_labelsize,
            "ytick.labelsize": preset.tick_labelsize,
            "pdf.fonttype": 42,
            "ps.fonttype": 42,
        },
    )

    fig, ax_left = plt.subplots(
        figsize=(preset.figure_width, preset.figure_height),
        constrained_layout=True,
    )
    ax_right = ax_left.twinx()

    line_complete_latency = ax_left.plot(
        turns,
        complete_latency_ms,
        color="#1f77b4",
        marker="o",
        linewidth=_PLOT_LINEWIDTH,
        markersize=_PLOT_MARKERSIZE,
        linestyle="-",
        label="Proactive - Latency",
    )[0]
    line_reactive_latency = ax_left.plot(
        turns,
        reactive_latency_ms,
        color="#d62728",
        marker="o",
        linestyle="-",
        linewidth=_PLOT_LINEWIDTH,
        markersize=_PLOT_MARKERSIZE,
        label="Reactive - Latency",
    )[0]
    line_complete_calls = ax_right.plot(
        turns,
        complete_cold_starts,
        color="#1f77b4",
        marker="s",
        linestyle="--",
        linewidth=_PLOT_LINEWIDTH,
        markersize=_PLOT_MARKERSIZE,
        label="Proactive - Cold",
    )[0]
    line_reactive_calls = ax_right.plot(
        turns,
        reactive_cold_starts,
        color="#d62728",
        marker="s",
        linestyle="--",
        linewidth=_PLOT_LINEWIDTH,
        markersize=_PLOT_MARKERSIZE,
        label="Reactive - Cold",
    )[0]

    ax_left.set_xlabel("Conversation Turn")
    ax_left.set_ylabel("Waiting Latency (ms)")
    ax_right.set_ylabel("Cold-Start Sandboxes")
    ax_left.set_xticks(turns)
    ax_left.set_xlim(1, max(turns))
    ax_left.set_ylim(0, max(650.0, max(reactive_latency_ms) * 1.08))
    ax_right.set_ylim(0, max(3.2, max(reactive_cold_starts) + 0.35))
    ax_left.grid(axis="y", linestyle=":", alpha=0.4)

    handles = [
        line_complete_latency,
        line_reactive_latency,
        line_complete_calls,
        line_reactive_calls,
    ]
    labels = [handle.get_label() for handle in handles]
    ax_left.legend(
        handles,
        labels,
        loc="upper center",
        bbox_to_anchor=(0.5, preset.legend_anchor_y),
        ncol=2,
        frameon=False,
        columnspacing=1.8,
        handlelength=2.6,
    )

    png_path = output_prefix.with_suffix(".png")
    pdf_path = output_prefix.with_suffix(".pdf")
    fig.savefig(png_path, dpi=300, bbox_inches="tight")
    fig.savefig(pdf_path, dpi=300, bbox_inches="tight")
    plt.close(fig)


def main() -> None:
    """CLI entrypoint for standalone plotting from artifacts."""
    parser = argparse.ArgumentParser(
        description="Replot SDG stochastic prefetching figure from CSV/JSON.",
    )
    parser.add_argument(
        "--csv",
        type=Path,
        default=_DEFAULT_CSV,
        help="Input CSV path.",
    )
    parser.add_argument(
        "--json",
        type=Path,
        default=_DEFAULT_JSON,
        help="Input JSON path for consistency validation.",
    )
    parser.add_argument(
        "--skip-json-check",
        action="store_true",
        help="Skip CSV/JSON consistency validation.",
    )
    parser.add_argument(
        "--output-prefix",
        type=Path,
        default=_DEFAULT_OUTPUT_PREFIX,
        help="Output prefix for PNG/PDF files.",
    )
    args = parser.parse_args()

    (
        turns,
        reactive_latency_ms,
        complete_latency_ms,
        reactive_cold_starts,
        complete_cold_starts,
    ) = _load_series_from_csv(args.csv)

    if not args.skip_json_check and args.json.exists():
        _validate_with_json(args.json, expected_turn_count=len(turns))

    args.output_prefix.parent.mkdir(parents=True, exist_ok=True)
    plot_dual_axis_figure(
        output_prefix=args.output_prefix,
        turns=turns,
        reactive_latency_ms=reactive_latency_ms,
        complete_latency_ms=complete_latency_ms,
        reactive_cold_starts=reactive_cold_starts,
        complete_cold_starts=complete_cold_starts,
    )

    print(str(args.output_prefix.with_suffix(".png")))
    print(str(args.output_prefix.with_suffix(".pdf")))


if __name__ == "__main__":
    main()
